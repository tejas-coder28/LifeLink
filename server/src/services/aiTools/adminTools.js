const analyticsService = require('../analytics.service');
const aiService = require('../ai.service');
const Hospital = require('../../repositories/hospital.repository');
const BloodRequest = require('../../repositories/bloodRequest.repository');

/**
 * Platform-wide governance and operational summary stats.
 */
async function getPlatformStats(context) {
  const analytics = await analyticsService.getSystemAnalytics();
  return {
    totalDonors: analytics.summary.totalDonors,
    availableDonors: analytics.summary.availableDonors,
    totalRequests: analytics.summary.totalRequests,
    fulfilledRequests: analytics.summary.fulfilledRequests,
    openRequests: analytics.summary.openRequests,
    fulfillmentRate: `${analytics.summary.fulfillmentRate}%`,
  };
}

/**
 * Returns hospitals pending administrator verification.
 */
async function getPendingHospitals(context) {
  const pending = await Hospital.find({ isVerified: false }).sort({ createdAt: -1 });

  return {
    pendingCount: pending.length,
    hospitals: pending.slice(0, 10).map((h) => ({
      id: h._id.toString(),
      name: h.name,
      phone: h.phone || '',
      address: h.address || '',
      registeredDate: h.createdAt ? new Date(h.createdAt).toISOString().split('T')[0] : '',
    })),
  };
}

/**
 * Returns blood supply shortages and risk alerts generated by the analytics / AI engine.
 */
async function getShortageAlerts(context) {
  const insight = await aiService.generateSystemInsight();
  return {
    title: insight.title,
    highRiskBloodGroups: insight.metrics?.highRiskBloodGroups || [],
    surplusGroups: insight.metrics?.surplusGroups || [],
    summary: insight.summary,
    recommendations: insight.recommendations || [],
  };
}

/**
 * Returns high-level overview of recent blood requests across all facilities.
 */
async function getRequestOverview(context) {
  const [total, open, requests] = await Promise.all([
    BloodRequest.countDocuments(),
    BloodRequest.countDocuments({ status: { $in: ['open', 'matching', 'partially_fulfilled'] } }),
    BloodRequest.find().sort({ createdAt: -1 }).limit(8).populate('targetHospital', 'name'),
  ]);

  return {
    totalRequests: total,
    activeRequestsCount: open,
    recentRequests: requests.map((r) => ({
      id: r._id.toString(),
      patientName: r.patientName,
      bloodGroup: r.bloodGroup,
      unitsNeeded: r.unitsNeeded,
      unitsFulfilled: r.unitsFulfilled || 0,
      urgency: r.urgency,
      status: r.status,
      hospitalName: r.targetHospital?.name || 'Unassigned',
      createdAt: r.createdAt ? new Date(r.createdAt).toISOString().split('T')[0] : '',
    })),
  };
}

module.exports = {
  getPlatformStats,
  getPendingHospitals,
  getShortageAlerts,
  getRequestOverview,
};
